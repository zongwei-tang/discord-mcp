#!/usr/bin/env node
import { realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';
import { ACCOUNT_FILE, VERSION, currentAccount, parseToken, saveAccount } from './config.js';
import { refreshBuildNumber } from './discord/client-props.js';
import { startGatewayInBackground } from './discord/gateway.js';
import { startQrLogin } from './discord/remote-auth.js';
import { rest } from './discord/rest.js';
import { endpoints } from './tools/catalog/endpoints.js';
import { applyMeta } from './tools/catalog/meta.js';
import { enabled, registerAll, tools } from './tools/registry.js';
import { buildAll } from './tools/spec.js';
import './tools/custom/account.js';
import './tools/custom/messaging.js';
import './tools/custom/navigation.js';
import './tools/custom/live.js';
import './tools/custom/interactions.js';
import './tools/custom/actions.js';

let built = false;
export function loadTools() {
  if (!built) { buildAll(applyMeta(endpoints)); built = true; }
  return tools;
}

export const INSTRUCTIONS = [
  'Discord as your own account (or a bot). "guild" = server. IDs are snowflake strings.',
  'Not logged in? Call discord_login and show the user the QR code to scan in the Discord phone app (Settings → Scan QR Code), then discord_login_status wait=true.',
  'Start with whoami, list_guilds, get_channel_tree, list_dms, list_unread. Read chats with read_messages, send with send_message (files: local paths/URLs), search with search_messages.',
  'Bots: list_commands / run_slash_command / click_button / select_menu_option / submit_modal. Live: get_events, wait_for_message, set_status, join_voice_channel.',
  'Most tools accept extra Discord API fields beyond those listed; discord_api_request reaches any route.',
].join(' ');

export function buildServer() {
  loadTools();
  const server = new McpServer({ name: 'discord-mcp', version: VERSION }, { instructions: INSTRUCTIONS });
  registerAll(server);
  return server;
}

async function cli(argv: string[]) {
  const [cmd, ...rest_] = argv;
  if (cmd === 'serve') {
    const { startHttpServer, MIN_TOKEN_LENGTH } = await import('./remote/http.js');
    const token = (process.env.MCP_AUTH_TOKEN || '').trim();
    if (token.length < MIN_TOKEN_LENGTH) {
      console.error(`discord-mcp serve: set MCP_AUTH_TOKEN (at least ${MIN_TOKEN_LENGTH} characters). Without it anyone could use your Discord account.`);
      process.exit(2);
    }
    const port = Number(process.env.PORT || 8000);
    const host = process.env.HOST || '0.0.0.0';
    loadTools();
    await startHttpServer({ host, port, token, buildServer, log: (l) => console.log(`[http] ${l}`) });
    console.log(`discord-mcp ${VERSION} listening on http://${host}:${port}/mcp (${tools.filter(enabled).length} tools)`);
    await refreshBuildNumber();
    startGatewayInBackground();
    return;
  }
  if (cmd === 'login') {
    if (rest_[0] === '--token') {
      const t = parseToken(rest_[1] ?? '', rest_.includes('--bot') ? 'bot' : undefined);
      const u = await rest.get('/users/@me', undefined, { account: t });
      saveAccount({ ...t, user: { id: u.id, username: u.username, global_name: u.global_name } });
      console.log(`Logged in as ${u.username} (${t.type}). Saved to ${ACCOUNT_FILE}`);
      return;
    }
    await refreshBuildNumber();
    const l = await startQrLogin();
    console.log(`\nScan this with the Discord phone app (avatar → Settings → Scan QR Code):\n\n${l.qrText}\n${l.url}\n\nWaiting…`);
    const tick = setInterval(() => { if (l.state === 'scanned') { console.log(`Scanned by ${l.user?.username} — confirm on your phone.`); clearInterval(tick); } }, 500);
    await l.done;
    clearInterval(tick);
    if (l.state === 'done') console.log(`Logged in as ${l.user?.username}. Saved to ${ACCOUNT_FILE}`);
    else { console.error(`Login ${l.state}: ${l.error ?? ''}`); process.exit(1); }
    process.exit(0);
  }
  if (cmd === 'token') {
    const a = currentAccount();
    if (!a) { console.error('Not logged in. Run: discord-mcp login'); process.exit(1); }
    console.log(a.type === 'bot' ? `Bot ${a.token}` : a.token);
    return;
  }
  if (cmd === 'status') {
    const a = currentAccount();
    if (!a) { console.log('Not logged in. Run: discord-mcp login'); return; }
    const u = await rest.get('/users/@me');
    console.log(`Logged in as ${u.username} (${a.type}), id ${u.id}`);
    return;
  }
  if (cmd === 'tools' && rest_.includes('--markdown')) {
    const ts = loadTools().filter(enabled);
    const cats = [...new Set(ts.map((t) => t.category))];
    const out = [`# Tools (${ts.length})\n`, 'Generated by `discord-mcp tools --markdown`. Endpoint tools show the Discord API route they call.\n'];
    for (const c of cats) {
      const list = ts.filter((t) => t.category === c);
      out.push(`\n## ${c} (${list.length})\n\n| Tool | What it does |\n| --- | --- |`);
      for (const t of list) out.push(`| \`${t.name}\` | ${t.description.replace(/\|/g, '\\|').replace(/ \[([A-Z]+ [^\]]+)\]$/, ' `$1`')} |`);
    }
    console.log(out.join('\n'));
    return;
  }
  if (cmd === 'tools') {
    const ts = loadTools().filter(enabled);
    const cats = new Map<string, number>();
    for (const t of ts) {
      cats.set(t.category, (cats.get(t.category) ?? 0) + 1);
      if (!rest_.includes('--count')) console.log(`${t.category.padEnd(13)} ${t.name.padEnd(46)} ${t.description.replace(/ \[[A-Z]+ [^\]]+\]$/, '').slice(0, 90)}`);
    }
    console.log(`\n${ts.length} tools: ${[...cats].map(([c, n]) => `${c} ${n}`).join(', ')}`);
    return;
  }
  if (cmd === '--version' || cmd === 'version') { console.log(VERSION); return; }
  console.log(`discord-mcp ${VERSION} — MCP server for Discord (personal account or bot)

  discord-mcp                       run the MCP server (stdio)
  discord-mcp login                 log in with a QR code (scan with the Discord phone app)
  discord-mcp login --token T       log in with a token (add --bot for bot tokens)
  discord-mcp status                show the logged-in account
  discord-mcp token                 print the saved token (to copy into DISCORD_TOKEN on a server)
  discord-mcp serve                 run the remote Streamable HTTP server (needs MCP_AUTH_TOKEN)
  discord-mcp tools [--count]       list tools`);
}

const isMain = (() => { try { return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url)); } catch { return false; } })();
const args = process.argv.slice(2);
if (!isMain) {
  // imported (tests)
} else if (args.length) {
  cli(args).catch((e) => { console.error(e.message); process.exit(1); });
} else {
  const server = buildServer();
  await server.connect(new StdioServerTransport());
  refreshBuildNumber().finally(() => startGatewayInBackground());
}
